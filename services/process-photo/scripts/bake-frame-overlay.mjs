#!/usr/bin/env node
/**
 * Bakes the curated 3-slot photo-strip frame into assets the Lambda can use.
 *
 * The source `assets/frames/curated/default.svg` is a fully-opaque artwork: the
 * three photo openings are NOT transparent holes. To composite photos *under*
 * the frame decorations (as `sample.svg` shows), we rasterize the SVG and punch
 * three transparent rectangles where the photos belong, producing an overlay
 * PNG. The slot rectangles (measured by diffing sample.svg against default.svg)
 * are the single source of truth here; this script emits both the overlay PNG
 * and `src/frame-layout.ts` so the Lambda and the asset stay in sync.
 *
 * Usage: node scripts/bake-frame-overlay.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../../..');

const SOURCE_SVG = path.join(repoRoot, 'assets/frames/curated/default.svg');
const OVERLAY_PNG = path.join(repoRoot, 'assets/frames/curated/default.png');
const LAYOUT_TS = path.join(here, '../src/frame-layout.ts');

// Reference space the slot rectangles were measured in (default.svg base px).
const BASE_WIDTH = 397;
const BASE_HEIGHT = 1123;

// Output canvas width; height preserves the strip aspect ratio.
const CANVAS_WIDTH = 1200;

// The three photo openings, inset 2px from the measured diff extents so the
// composited photos stay inside the torn border artwork.
const BASE_SLOTS = [
  { x: 27, y: 103, width: 338, height: 201 },
  { x: 25, y: 337, width: 339, height: 199 },
  { x: 26, y: 573, width: 340, height: 202 },
];

function main() {
  const scale = CANVAS_WIDTH / BASE_WIDTH;
  const canvasHeight = Math.round(BASE_HEIGHT * scale);

  const slots = BASE_SLOTS.map((slot) => ({
    x: Math.round(slot.x * scale),
    y: Math.round(slot.y * scale),
    width: Math.round(slot.width * scale),
    height: Math.round(slot.height * scale),
  }));

  return sharp(SOURCE_SVG)
    .resize(CANVAS_WIDTH, canvasHeight)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true })
    .then(async ({ data, info }) => {
      // Punch transparent holes at each slot opening.
      for (const slot of slots) {
        for (let y = slot.y; y < slot.y + slot.height; y++) {
          for (let x = slot.x; x < slot.x + slot.width; x++) {
            const i = (y * info.width + x) * 4;
            data[i + 3] = 0;
          }
        }
      }

      await sharp(data, { raw: { width: info.width, height: info.height, channels: 4 } })
        .png()
        .toFile(OVERLAY_PNG);

      const layoutSource = `// GENERATED by scripts/bake-frame-overlay.mjs - do not edit by hand.
// Slot rectangles for the curated 3-slot photo-strip frame overlay
// (assets/frames/curated/default.png), in canvas pixel coordinates.

export interface SlotRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface FrameLayout {
  width: number;
  height: number;
  slots: SlotRect[];
}

export const FRAME_LAYOUT: FrameLayout = {
  width: ${CANVAS_WIDTH},
  height: ${canvasHeight},
  slots: ${JSON.stringify(slots, null, 2).replace(/\n/g, '\n  ')},
};

export const SHOT_COUNT = FRAME_LAYOUT.slots.length;
`;

      await writeFile(LAYOUT_TS, layoutSource, 'utf8');

      console.log(`Wrote overlay: ${OVERLAY_PNG} (${CANVAS_WIDTH}x${canvasHeight})`);
      console.log(`Wrote layout:  ${LAYOUT_TS}`);
      console.log('Slots:', JSON.stringify(slots));
    });
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
